// Standard even-odd ray casting, cast in the longitude direction at a fixed
// latitude. Running it across every ring at once is what makes the holes work:
// a point inside Glendale crosses the outer ring an odd number of times and the
// Glendale ring once more, which flips it back to outside.
function isPointInsideDenver([latitude, longitude]) {
  let inside = false;
  for (const ring of DENVER_CITY_LIMITS) {
    for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index++) {
      const [currentLat, currentLon] = ring[index];
      const [previousLat, previousLon] = ring[previous];
      const straddles = currentLat > latitude !== previousLat > latitude;
      if (!straddles) continue;
      const crossing = ((previousLon - currentLon) * (latitude - currentLat)) / (previousLat - currentLat) + currentLon;
      if (longitude < crossing) inside = !inside;
    }
  }
  return inside;
}

// Metres per degree at Denver's latitude. The city spans a third of a degree of
// latitude, so these drift by a few tenths of a percent corner to corner — an
// error of centimetres on the 20 m buffer, which is not worth a projection.
const METRES_PER_DEGREE_LATITUDE = 111320;
const METRES_PER_DEGREE_LONGITUDE = 85700;

function metresToSegment([latitude, longitude], [aLat, aLon], [bLat, bLon]) {
  const x = (longitude - aLon) * METRES_PER_DEGREE_LONGITUDE;
  const y = (latitude - aLat) * METRES_PER_DEGREE_LATITUDE;
  const dx = (bLon - aLon) * METRES_PER_DEGREE_LONGITUDE;
  const dy = (bLat - aLat) * METRES_PER_DEGREE_LATITUDE;
  const lengthSquared = dx * dx + dy * dy;
  const t = lengthSquared ? Math.max(0, Math.min(1, (x * dx + y * dy) / lengthSquared)) : 0;
  return Math.hypot(x - t * dx, y - t * dy);
}

// Denver's ring is a thousand points where Glendale's was seventy, and the
// importer asks this question for every sampled point of every block in an
// area. Rejecting a segment on its bounding box first — the point cannot be
// nearer than its distance to that box — skips almost all of them, since the
// nearest piece of the city line is usually a few hundred metres away and the
// rest of the boundary is kilometres off.
function metresToRings(point) {
  let nearest = Infinity;
  for (const ring of DENVER_CITY_LIMITS) {
    for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index++) {
      const current = ring[index];
      const prior = ring[previous];
      const latitudeGap = Math.max(Math.min(current[0], prior[0]) - point[0], point[0] - Math.max(current[0], prior[0]), 0);
      const longitudeGap = Math.max(Math.min(current[1], prior[1]) - point[1], point[1] - Math.max(current[1], prior[1]), 0);
      const lowerBound = Math.hypot(latitudeGap * METRES_PER_DEGREE_LATITUDE, longitudeGap * METRES_PER_DEGREE_LONGITUDE);
      if (lowerBound >= nearest) continue;
      nearest = Math.min(nearest, metresToSegment(point, current, prior));
    }
  }
  return nearest;
}

function metresOutsideDenver(point) {
  if (isPointInsideDenver(point)) return 0;
  return metresToRings(point);
}

// Denver's boundary is drawn down the middle of the streets that carry it —
// South Yosemite Street, South Havana Street, East Hampden Avenue and East
// Yale Avenue among them — and Denver sweeps its own side of every one. A plain
// inside/outside test puts roughly half of those streets' sampled points across
// the line and throws away real coverage, so a block only counts as another
// city's when most of it sits well clear of the line. Twenty metres is wider
// than any half-roadway on the boundary and far narrower than the shortest
// interior block, and it is the same figure the Glendale test uses.
const BOUNDARY_BUFFER_METRES = 20;

function isOutsideDenverBlock(geometry) {
  if (!Array.isArray(geometry) || !geometry.length) return false;
  const wellOutside = geometry.filter((point) => metresOutsideDenver(point) > BOUNDARY_BUFFER_METRES).length;
  return wellOutside * 2 > geometry.length;
}

