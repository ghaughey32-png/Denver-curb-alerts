// Reclassifies the already-published inventory without asking Denver for
// anything, so a change to the offline matching logic can ship without a
// city-wide crawl.
//
// build:inventory does two separate jobs in one command: it crawls Denver's
// sweeping API for the whole city, and then it runs the offline pipeline that
// turns those routes into the published payload. Changes to the offline half --
// the auditor's street-name matching, the coverage patches, the classification
// rules -- need no new data from Denver, because the routes already in
// public/denver-west-routes.json are the same routes a fresh crawl returns.
// Denver rate-limits the crawl aggressively, so reprocessing what we already
// have is both faster and kinder to a small municipal API.
//
// Use build:inventory instead whenever you actually want fresh data from Denver:
// schedule changes, new or retired routes, seasonal updates, or a pilot area
// that has never been crawled. This script cannot discover any of that.
//
// The scope is deliberately narrow: reclassify, and withdraw a pink
// `dataUnavailable` route when its block now resolves to a real schedule.
// Nothing else about the published payload changes.
//
// It does not invent new pink coverage. Reprocessing brings no new knowledge
// about a block, so a block that has never had a published route has nothing
// here to justify drawing one -- and several are unpublished by deliberate
// product decision (see the Tennyson and Yates cases in
// test/inventory-coverage.test.js).
//
// It also does not re-run the coverage patches in build-static-inventory.js.
// Those patches are written against the state of a fresh crawl and several are
// guarded with `if (routeMap.has(id)) return`, so replaying them over an
// already-published payload mixes in whatever patch changes have accumulated
// since the last real crawl instead of only the change you are shipping. Run
// build:inventory when you change a patch.
//
// So a clean run here is a weaker statement than a clean build:inventory: it
// means "the classifier agrees with the data we already have", not "the map is
// complete and every patch is applied".

const fs = require("fs/promises");
const { auditInventory } = require("./lib/inventory-auditor.js");
const {
  writeInventoryArtifacts,
  EXPECTED_BLOCKS_PATH,
  OUTPUT_PATH
} = require("./build-static-inventory.js");

// The exact note inventory-auditor.js stamps on every route it generates for an
// uncovered block. Only these are ours to withdraw; a hand-curated pink route
// from a confirmed-*-coverage module must survive untouched.
const AUDITOR_GENERATED_NOTE =
  "Generated by the inventory auditor because a public roadway exists here but Denver returned no usable schedule.";

async function main() {
  const [expectedBlockManifest, published] = await Promise.all([
    fs.readFile(EXPECTED_BLOCKS_PATH, "utf8").then(JSON.parse),
    fs.readFile(OUTPUT_PATH, "utf8").then(JSON.parse)
  ]);

  const routeMap = new Map(published.routes.map((route) => [route.id, route]));

  // generateUnavailable stays false so the audit reports what the current data
  // supports instead of manufacturing fallbacks for never-covered blocks.
  const auditOptions = { blocks: expectedBlockManifest.blocks, generateUnavailable: false };
  const before = auditInventory({ routes: routeMap, ...auditOptions });

  const scheduledBlockIds = new Set(
    before.report.blocks.filter((block) => block.status === "scheduled").map((block) => block.id)
  );
  // A pink route drawn for one block can be the only thing covering a
  // neighbouring block, because the auditor accepts any dataUnavailable route
  // whose geometry runs along the block. Withdrawing such a route because its
  // own block is now scheduled would leave the neighbour rendering blank, which
  // breaks the product invariant. Keep anything another uncovered block leans on.
  const claimedByAnotherBlock = new Set(
    before.report.blocks
      .filter((block) => block.status === "unavailable")
      .flatMap((block) => block.routeIds || [])
  );

  const withdrawn = [];
  routeMap.forEach((route, id) => {
    if (route.sourceNote !== AUDITOR_GENERATED_NOTE) return;
    if (!scheduledBlockIds.has(route.expectedBlockId)) return;
    if (claimedByAnotherBlock.has(id)) return;
    routeMap.delete(id);
    withdrawn.push(route.expectedBlockId);
  });

  // Re-audit so the published report describes what actually shipped, and so a
  // withdrawal that orphaned a block is caught here rather than on the map.
  const after = auditInventory({ routes: routeMap, ...auditOptions });
  const gapsBefore = new Set(before.unexplainedGaps.map((block) => block.id));
  const orphaned = after.unexplainedGaps.filter((block) => !gapsBefore.has(block.id));
  if (orphaned.length) {
    throw new Error(
      `Refusing to publish: withdrawing fallbacks left ${orphaned.length} block(s) with no coverage: ${orphaned.map((block) => block.id).join(", ")}`
    );
  }

  const coverageReport = {
    ...after.report,
    generatedAt: new Date().toISOString(),
    expectedBlockManifestVersion: expectedBlockManifest.version
  };

  console.log(
    `Reprocessed ${published.routes.length} published routes; ${withdrawn.length} block(s) now resolve to a real Denver schedule and had their pink fallback withdrawn.`
  );
  if (after.unexplainedGaps.length) {
    // Not fatal here, unlike build:inventory. These are blocks the published
    // data has never covered, which is exactly what this script cannot fix.
    console.log(`${after.unexplainedGaps.length} block(s) remain without coverage; only build:inventory can resolve those.`);
  }

  await writeInventoryArtifacts(routeMap, coverageReport);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
