async function sendImmediateTestNotification(job = null) {
  if (!canUseBrowserNotifications()) {
    renderNotificationStatus();
    return;
  }

  if (hasRemotePushReady()) {
    try {
      const sent = await sendPushTestRequest(job);
      if (sent) {
        return;
      }
    } catch {
      // Fall back to a local preview notification below.
    }
  }

  if (window.Notification.permission !== "granted") {
    await requestBrowserNotifications();
    return;
  }

  const previewJob = job || state.notificationJobs[0];
  if (previewJob) {
    deliverNotificationJob(previewJob.id, { preview: true });
    return;
  }

  new window.Notification("Street sweeping reminder test", {
    body: "Test alert: this is how your move-your-car reminder will look."
  });
}

