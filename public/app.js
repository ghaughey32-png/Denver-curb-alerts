function applySavedSet(setId) {
  const savedSet = state.savedSets.find((set) => set.id === setId);
  if (!savedSet) {
    return;
  }

  const availableIds = new Set(state.curbSegments.map((segment) => segment.id));
  const matchingIds = getSegmentsForSavedSet(savedSet).map((segment) => segment.id).filter((id) => availableIds.has(id));

  if (!matchingIds.length && savedSet.lookupAddress) {
    state.pendingApplySetId = setId;
    loadDenverLookup(savedSet.lookupAddress, savedSet.sourceLabel || savedSet.name, { applySetId: setId });
    return;
  }

  state.currentSelectionIds = matchingIds;
  saveJson(CURRENT_SELECTION_KEY, state.currentSelectionIds);
  renderAll();
}

function deleteSavedSet(setId) {
  state.savedSets = state.savedSets.filter((set) => set.id !== setId);
  saveJson(SAVED_SETS_KEY, state.savedSets);
  renderAll();
}

function updateSavedSet(setId, updates) {
  let changed = false;

  state.savedSets = state.savedSets.map((set) => {
    if (set.id !== setId) {
      return set;
    }

    changed = true;
    const nextReminders = updates.reminders ? buildDefaultReminders({ ...set.reminders, ...updates.reminders }) : set.reminders;
    return {
      ...set,
      ...updates,
      reminders: nextReminders
    };
  });

  if (!changed) {
    return;
  }

  saveJson(SAVED_SETS_KEY, state.savedSets);
  renderAll();
}

function getUpcomingSweepDates(segment) {
  const seen = new Set();
  const upcomingDates = [];
  const today = getStartOfToday();

  const addDate = (dateValue) => {
    const sweepDate = dateValue instanceof Date ? dateValue : parseSweepDate(dateValue);
    if (!sweepDate) {
      return;
    }

    if (sweepDate.getTime() < today.getTime()) {
      return;
    }

    const normalizedKey = sweepDate.toISOString().slice(0, 10);
    if (seen.has(normalizedKey)) {
      return;
    }

    seen.add(normalizedKey);
    upcomingDates.push(sweepDate);
  };

  const allDates = Array.isArray(segment.schedule?.allDates) ? segment.schedule.allDates : [];
  allDates.forEach((item) => addDate(item?.Date));
  addDate(segment.schedule?.nextDate);
  getRuleBasedSweepDates(segment).forEach(addDate);

  return upcomingDates.sort((a, b) => a.getTime() - b.getTime()).slice(0, 8);
}

function getNextSweepDate(segment) {
  return getUpcomingSweepDates(segment)[0] || null;
}

function getRuleBasedSweepDates(segment, monthCount = 8) {
  const rule = parseMonthlySweepRule(segment.schedule?.rule);
  if (!rule) {
    return [];
  }

  const dates = [];
  const today = getStartOfToday();
  const startMonth = new Date(today.getFullYear(), today.getMonth(), 1);

  for (let offset = 0; offset < monthCount; offset += 1) {
    const targetMonth = new Date(startMonth.getFullYear(), startMonth.getMonth() + offset, 1);
    const sweepDate = getMonthlyOrdinalWeekdayDate(
      targetMonth.getFullYear(),
      targetMonth.getMonth(),
      rule.ordinal,
      rule.weekdayIndex
    );

    if (sweepDate && sweepDate.getTime() >= today.getTime()) {
      dates.push(sweepDate);
    }
  }

  return dates;
}

function parseMonthlySweepRule(ruleText) {
  const match = String(ruleText || "").match(
    /(?:the\s+)?(\d+)(?:st|nd|rd|th)\s+(monday|tuesday|wednesday|thursday|friday|saturday|sunday)\s+of\s+the\s+month/i
  );

  if (!match) {
    return null;
  }

  const weekdayMap = {
    sunday: 0,
    monday: 1,
    tuesday: 2,
    wednesday: 3,
    thursday: 4,
    friday: 5,
    saturday: 6
  };

  const ordinal = Number(match[1]);
  const weekdayIndex = weekdayMap[match[2].toLowerCase()];
  if (!ordinal || weekdayIndex === undefined) {
    return null;
  }

  return { ordinal, weekdayIndex };
}

function getMonthlyOrdinalWeekdayDate(year, monthIndex, ordinal, weekdayIndex) {
  const firstDay = new Date(year, monthIndex, 1, 0, 0, 0, 0);
  const daysUntilWeekday = (weekdayIndex - firstDay.getDay() + 7) % 7;
  const dayOfMonth = 1 + daysUntilWeekday + (ordinal - 1) * 7;
  const candidate = new Date(year, monthIndex, dayOfMonth, 0, 0, 0, 0);

  if (candidate.getMonth() !== monthIndex) {
    return null;
  }

  return candidate;
}

function getStartOfToday() {
  const now = new Date();
  return new Date(now.getFullYear(), now.getMonth(), now.getDate(), 0, 0, 0, 0);
}

function updateDayOfReminder(setId, slotIndex, field, value) {
  const savedSet = state.savedSets.find((set) => set.id === setId);
  if (!savedSet) {
    return;
  }

  const nextSlots = buildDefaultReminders(savedSet.reminders).dayOfReminders.map((slot, index) =>
    index === slotIndex ? { ...slot, [field]: value } : slot
  );

  updateSavedSet(setId, {
    reminders: {
      dayOfReminders: nextSlots
    }
  });
}

function buildDefaultSetName(segments, fallbackNumber) {
  const validSegments = segments.filter(Boolean);
  if (!validSegments.length) {
    return `Parking reminder ${fallbackNumber}`;
  }

  if (validSegments.length === 1) {
    return `${validSegments[0].street} - ${validSegments[0].sideLabel}`;
  }

  const streetNames = [...new Set(validSegments.map((segment) => segment.street).filter(Boolean))];
  if (streetNames.length === 1) {
    return `${streetNames[0]} - ${validSegments.length} curb sides`;
  }

  return `${streetNames[0]} + ${streetNames.length - 1} more streets`;
}

function summarizeSavedSetMeta(segments) {
  const count = segments.filter(Boolean).length;
  return `${count} ${count === 1 ? "curb side" : "curb sides"} selected`;
}

function buildSavedSetDetails(set, segments, reminders) {
  const detailRows = [
    ["Next sweep", summarizeSetSchedule(segments)],
    ["Curbs", summarizeCurbList(segments)],
    ["Reminders", summarizeReminders(reminders).replace(/^Scheduled /, "")],
    ["Area", set.sourceLabel || "Saved curb set"],
    ["Saved", formatSavedAt(set.createdAt)]
  ];

  return detailRows
    .map(
      ([label, value]) => `
        <div class="saved-set-detail-row">
          <span class="saved-set-detail-label">${escapeHtml(label)}</span>
          <span>${escapeHtml(value)}</span>
        </div>
      `
    )
    .join("");
}

function summarizeCurbList(segments) {
  const curbs = segments.filter(Boolean).map((segment) => `${segment.sideLabel} of ${segment.street}`);
  if (!curbs.length) {
    return "No curb sides found";
  }

  const visibleCurbs = curbs.slice(0, 3);
  const hiddenCount = curbs.length - visibleCurbs.length;
  return hiddenCount ? `${visibleCurbs.join(", ")} and ${hiddenCount} more` : visibleCurbs.join(", ");
}

function formatSavedAt(createdAt) {
  const date = new Date(createdAt);
  if (Number.isNaN(date.getTime())) {
    return "Saved recently";
  }

  return date.toLocaleString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit"
  });
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

