function summarizeSetSchedule(segments) {
  const dates = segments
    .filter(Boolean)
    .flatMap((segment) => getUpcomingSweepDates(segment))
    .sort((a, b) => a.getTime() - b.getTime());

  if (!dates.length) {
    return "No dated sweep found";
  }

  return `Earliest: ${formatDateObject(dates[0])}`;
}

function summarizeReminders(reminders) {
  const parts = [];
  const activeDayOfTimes = reminders.dayOfReminders.filter((slot) => slot.enabled).map((slot) => formatTime(slot.time));

  if (reminders.dayBeforeEnabled) {
    parts.push(`day before at ${formatTime(reminders.dayBeforeTime)}`);
  }

  if (activeDayOfTimes.length) {
    parts.push(`day of at ${activeDayOfTimes.join(", ")}`);
  }

  if (!parts.length) {
    return "Reminders are turned off for this set.";
  }

  return `Scheduled ${parts.join(" and ")}.`;
}

function formatTime(timeValue) {
  if (!isValidTimeValue(timeValue)) {
    return "an unset time";
  }

  const [hourText, minuteText] = timeValue.split(":");
  const hour = Number(hourText);
  const minute = Number(minuteText);
  const date = new Date(2026, 0, 1, hour, minute, 0);
  return date.toLocaleTimeString("en-US", {
    hour: "numeric",
    minute: "2-digit"
  });
}

function formatDateObject(date) {
  return date.toLocaleDateString("en-US", {
    weekday: "short",
    month: "short",
    day: "numeric",
    year: "numeric"
  });
}

