function buildIssueReportPayload() {
  const selectedSegments = getSelectedSegments().map((segment) => {
    const nextSweepDate = getNextSweepDate(segment);

    return {
      id: segment.id,
      street: segment.street,
      sideKey: segment.sideKey,
      sideLabel: segment.sideLabel,
      nextSweep: nextSweepDate ? formatDateObject(nextSweepDate) : "",
      rule: segment.schedule?.rule || "",
      source: segment.source || state.activeSourceLabel
    };
  });

  return {
    type: issueTypeSelect?.value || "Something else",
    note: issueNoteInput?.value.trim() || "",
    selectedSegments,
    selectionCount: selectedSegments.length,
    savedSetCount: state.savedSets.length,
    jobCount: state.notificationJobs.length,
    pushConnected: Boolean(state.pushSubscription),
    hasUserLocation: Boolean(state.userLocation),
    activeAreaLabel: state.activeAreaLabel,
    activeSourceLabel: state.activeSourceLabel,
    pageUrl: window.location.href,
    userAgent: navigator.userAgent,
    viewport: {
      width: window.innerWidth,
      height: window.innerHeight
    },
    createdAtClient: new Date().toISOString()
  };
}

async function submitIssueReport(event) {
  event.preventDefault();

  const payload = buildIssueReportPayload();
  if (!payload.note) {
    setIssueReportStatus("Add a quick note first so we know what to fix.", true);
    issueNoteInput?.focus();
    return;
  }

  if (submitIssueButton) {
    submitIssueButton.disabled = true;
  }
  setIssueReportStatus("Sending your report...");

  try {
    const response = await fetch(buildApiUrl("/api/issue-reports"), {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });
    const result = await response.json().catch(() => ({}));

    if (!response.ok) {
      throw new Error(result.error || "Unable to save issue report.");
    }

    if (issueNoteInput) {
      issueNoteInput.value = "";
    }
    setIssueReportStatus("Thanks. We saved that issue report.");
  } catch (error) {
    setIssueReportStatus(error.message || "We couldn't send that report yet. Try again in a minute.", true);
  } finally {
    if (submitIssueButton) {
      submitIssueButton.disabled = false;
    }
  }
}

function renderSavedSets() {
  savedSetsList.innerHTML = "";
  savedSetCount.textContent = `${state.savedSets.length} saved`;
  emptySets.style.display = state.savedSets.length ? "none" : "block";

  state.savedSets
    .slice()
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
    .forEach((set) => {
      const item = savedSetTemplate.content.firstElementChild.cloneNode(true);
      const reminders = buildDefaultReminders(set.reminders);
      const savedSegments = getSegmentsForSavedSet(set);
      item.querySelector(".saved-set-title").textContent = set.name;
      item.querySelector(".saved-set-meta").textContent = summarizeSavedSetMeta(savedSegments);
      item.querySelector(".saved-set-details").innerHTML = buildSavedSetDetails(set, savedSegments, reminders);
      item.querySelector(".reminder-summary").textContent = summarizeReminders(reminders);

      const dayBeforeEnabledInput = item.querySelector(".day-before-enabled");
      const dayBeforeTimeInput = item.querySelector(".day-before-time");
      const dayOfEnabledInputs = Array.from(item.querySelectorAll(".day-of-enabled"));
      const dayOfTimeInputs = Array.from(item.querySelectorAll(".day-of-time"));

      dayBeforeEnabledInput.checked = reminders.dayBeforeEnabled;
      dayBeforeTimeInput.value = reminders.dayBeforeTime;
      dayBeforeTimeInput.disabled = !reminders.dayBeforeEnabled;

      reminders.dayOfReminders.forEach((slot, index) => {
        const enabledInput = dayOfEnabledInputs[index];
        const timeInput = dayOfTimeInputs[index];
        if (!enabledInput || !timeInput) {
          return;
        }

        enabledInput.checked = slot.enabled;
        timeInput.value = slot.time;
        timeInput.disabled = !slot.enabled;
      });

      dayBeforeEnabledInput.addEventListener("change", () =>
        updateSavedSet(set.id, {
          reminders: {
            dayBeforeEnabled: dayBeforeEnabledInput.checked
          }
        })
      );
      dayBeforeTimeInput.addEventListener("change", () =>
        updateSavedSet(set.id, {
          reminders: {
            dayBeforeTime: dayBeforeTimeInput.value
          }
        })
      );
      dayOfEnabledInputs.forEach((input, index) => {
        input.addEventListener("change", () => updateDayOfReminder(set.id, index, "enabled", input.checked));
      });
      dayOfTimeInputs.forEach((input, index) => {
        input.addEventListener("change", () => updateDayOfReminder(set.id, index, "time", input.value));
      });

      item.querySelector(".apply-set-button").addEventListener("click", () => applySavedSet(set.id));
      item.querySelector(".delete-set-button").addEventListener("click", () => deleteSavedSet(set.id));
      savedSetsList.appendChild(item);
    });
}

function buildNotificationJobs() {
  const now = new Date();
  const groupedJobs = new Map();

  state.savedSets.forEach((set) => {
    const reminders = buildDefaultReminders(set.reminders);
    const selectedSegments = getSegmentsForSavedSet(set);

    selectedSegments.forEach((segment) => {
      const sweepDates = getUpcomingSweepDates(segment);
      if (!sweepDates.length) {
        return;
      }

      sweepDates.forEach((sweepDate) => {
        const candidates = [];

        if (reminders.dayBeforeEnabled) {
          candidates.push({
            kind: "day-before",
            label: "Day before",
            scheduledAt: applyTimeToDate(addDays(sweepDate, -1), reminders.dayBeforeTime)
          });
        }

        reminders.dayOfReminders.forEach((slot, index) => {
          if (!slot.enabled) {
            return;
          }

          candidates.push({
            kind: "day-of",
            label: `Day of reminder ${index + 1}`,
            scheduledAt: applyTimeToDate(sweepDate, slot.time)
          });
        });

        candidates.forEach((candidate) => {
          if (!candidate.scheduledAt || candidate.scheduledAt.getTime() <= now.getTime()) {
            return;
          }

          const groupKey = `${set.id}|${candidate.scheduledAt.toISOString()}`;
          if (!groupedJobs.has(groupKey)) {
            groupedJobs.set(groupKey, {
              id: `job-${groupKey}`,
              setId: set.id,
              setName: set.name,
              scheduledAt: candidate.scheduledAt.toISOString(),
              segmentIds: [],
              segmentLabels: [],
              triggerLabels: []
            });
          }

          const job = groupedJobs.get(groupKey);
          if (!job.segmentIds.includes(segment.id)) {
            job.segmentIds.push(segment.id);
            job.segmentLabels.push(`${segment.street} - ${segment.sideLabel}`);
          }

          if (!job.triggerLabels.includes(candidate.label)) {
            job.triggerLabels.push(candidate.label);
          }
        });
      });
    });
  });

  state.notificationJobs = Array.from(groupedJobs.values())
    .map((job) => ({
      ...job,
      title: buildJobTitle(job),
      body: buildJobBody(job)
    }))
    .sort((a, b) => new Date(a.scheduledAt) - new Date(b.scheduledAt));

  saveJson(NOTIFICATION_JOBS_KEY, state.notificationJobs);
}

