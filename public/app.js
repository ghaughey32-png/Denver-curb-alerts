async function searchAddressAndCenter(address) {
  const cleanedAddress = String(address || "").trim();
  if (!cleanedAddress) {
    if (lookupStatus) {
      lookupStatus.textContent = "Enter an address or cross streets first, then we'll jump the map there.";
    }
    lookupAddressInput?.focus();
    return;
  }

  if (lookupStatus) {
    lookupStatus.textContent = `Searching for ${cleanedAddress}...`;
  }
  if (lookupAddressButton) {
    lookupAddressButton.disabled = true;
  }

  try {
    let denverLookupError = "";
    const searchQuery = normalizeDenverSearchQuery(cleanedAddress);
    const response = await fetch(buildAddressLookupUrl(searchQuery));
    if (response.ok) {
      const summary = await response.json();
      const center = getLookupCenter(summary);

      if (center && isWithinDenverBounds(center.lat, center.lon)) {
        state.searchedLocation = { ...center, label: cleanedAddress };
        renderContext();
        focusMapOnSearchedLocation();

        if (lookupAddressInput) {
          lookupAddressInput.value = cleanedAddress;
        }
        if (lookupStatus) {
          lookupStatus.textContent = `Found it. The map is centered near ${cleanedAddress}. Tap a colored curb nearby to select reminders.`;
        }
        return;
      }

      denverLookupError = "Denver found the address, but did not send back a map point we can use.";
    } else {
      denverLookupError = await getFriendlyLookupError(response);
    }

    const localMatch = findLocalSearchMatch(cleanedAddress);
    if (!localMatch || !isWithinDenverBounds(localMatch.lat, localMatch.lon)) {
      throw new Error(
        `${denverLookupError} Try a Sloan's Lake street or cross street, like "23rd and King" or "Lowell and 17th".`
      );
    }

    state.searchedLocation = { ...localMatch, label: localMatch.label || cleanedAddress };
    renderContext();
    focusMapOnSearchedLocation();

    if (lookupAddressInput) {
      lookupAddressInput.value = cleanedAddress;
    }
    if (lookupStatus) {
      lookupStatus.textContent = `Denver's lookup was unavailable, so I matched this to ${localMatch.matchedStreet} in the Sloan's Lake map. Tap a colored curb nearby to select reminders.`;
    }
  } catch (error) {
    if (lookupStatus) {
      lookupStatus.textContent = error.message || "Unable to find that spot right now.";
    }
  } finally {
    if (lookupAddressButton) {
      lookupAddressButton.disabled = false;
    }
  }
}

async function loadDenverLookup(address, sourceLabel = "Live Denver lookup", options = {}) {
  const cleanedAddress = String(address || "").trim();
  if (!cleanedAddress) {
    if (lookupStatus) {
      lookupStatus.textContent = "Enter an address first so we know which neighborhood to load.";
    }
    return;
  }

  if (lookupStatus) {
    lookupStatus.textContent = `Loading live sweeping routes near ${cleanedAddress}...`;
  }
  if (lookupAddressButton) {
    lookupAddressButton.disabled = true;
  }

  try {
    const response = await fetch(buildApiUrl(`/api/denver/sweeping?address=${encodeURIComponent(cleanedAddress)}`));
    if (!response.ok) {
      const details = await response.text();
      throw new Error(details || "Unable to load Denver sweeping routes for that address.");
    }

    const summary = await response.json();
    const { streetWays, curbSegments, context } = buildLookupStreetData(summary, sourceLabel);
    if (!streetWays.length || !curbSegments.length) {
      throw new Error("Denver returned this address, but not enough route geometry to draw a neighborhood map yet.");
    }

    setMapDataset({
      streetWays,
      curbSegments,
      areaLabel: cleanedAddress,
      geometryLabel: `Live Denver route segments (${summary.routeCount || curbSegments.length} returned)`,
      mapTitleText: `${sourceLabel} live map`,
      mapKickerText: "Denver live lookup",
      sourceLabel,
      lookupAddress: cleanedAddress,
      context,
      mapNoteText:
        "These curb lines came from Denver's live sweeping lookup for the address you loaded. Save any side you want reminders for, then the hosted reminder system will treat it just like the pilot blocks."
    });

    const applySetId = options.applySetId || state.pendingApplySetId;
    if (applySetId) {
      const savedSet = state.savedSets.find((set) => set.id === applySetId);
      const availableIds = new Set(state.curbSegments.map((segment) => segment.id));
      const matchingIds = savedSet ? getSegmentsForSavedSet(savedSet).map((segment) => segment.id).filter((id) => availableIds.has(id)) : [];
      state.currentSelectionIds = matchingIds;
      saveJson(CURRENT_SELECTION_KEY, state.currentSelectionIds);
      state.pendingApplySetId = "";
    }

    refreshMapViewport();
    renderAll();

    if (lookupAddressInput) {
      lookupAddressInput.value = cleanedAddress;
    }
    if (lookupStatus) {
      lookupStatus.innerHTML = `<strong>${sourceLabel}</strong> is loaded from Denver's live sweeping service around ${cleanedAddress}.`;
    }
  } catch (error) {
    if (lookupStatus) {
      lookupStatus.textContent = error.message || "Unable to load that Denver area right now.";
    }
  } finally {
    if (lookupAddressButton) {
      lookupAddressButton.disabled = false;
    }
  }
}

function requestUserLocation() {
  if (!lookupStatus || !useMyLocationButton) {
    return;
  }

  if (!canUseGeolocation()) {
    lookupStatus.textContent = "This browser cannot share your location yet, so keep using the map with your fingers for now.";
    return;
  }

  if (!isSecureHost()) {
    lookupStatus.textContent = "Location only works on the hosted app or localhost. This local file preview cannot ask for your location.";
    return;
  }

  useMyLocationButton.disabled = true;
  lookupStatus.textContent = "Finding your location in Denver now...";

  navigator.geolocation.getCurrentPosition(
    (position) => {
      const { latitude, longitude } = position.coords;

      if (!isWithinDenverBounds(latitude, longitude)) {
        useMyLocationButton.disabled = false;
        lookupStatus.textContent =
          "We found you, but you look outside the Denver map area right now. You can still pan around Denver and tap curb sides manually.";
        return;
      }

      state.userLocation = { lat: latitude, lon: longitude };
      renderContext();
      focusMapOnUserLocation();
      lookupStatus.textContent = "You're on the map now. We dropped a dot at your location so you can tap nearby curbs more easily.";
      useMyLocationButton.disabled = false;
    },
    (error) => {
      useMyLocationButton.disabled = false;

      if (error.code === error.PERMISSION_DENIED) {
        lookupStatus.textContent = "We can only center on you if you allow location access. You can still move around the map manually.";
        return;
      }

      if (error.code === error.TIMEOUT) {
        lookupStatus.textContent = "We couldn't find your location quickly enough. Try again in a moment, or keep exploring the map manually.";
        return;
      }

      lookupStatus.textContent = "We hit a snag trying to find your location. You can still move around the map manually for now.";
    },
    {
      enableHighAccuracy: true,
      timeout: 12000,
      maximumAge: 60000
    }
  );
}

