  // The wash is the line pushed out by this much, so a curb on the line itself is never painted
  // over. Denver and Minneapolis do the same with 20 m.
  const BOUNDARY_BUFFER_METRES = 20;
  const METRES_PER_DEGREE_LAT = 111320;

  let maskRings = null;

  // Pushes every vertex outward along the bisector of its two edges. The ring is simple, so a vertex
  // offset is exact enough at 20 m.
  function getMaskRings() {
    if (maskRings) return maskRings;

    maskRings = CITY_LIMITS.map((ring) => {
      let area = 0;
      for (let i = 0; i < ring.length; i += 1) {
        const a = ring[i];
        const b = ring[(i + 1) % ring.length];
        area += a[1] * b[0] - b[1] * a[0];
      }
      const outwardSign = area > 0 ? 1 : -1;
      const cosLat = Math.cos((ring[0][0] * Math.PI) / 180);
      return ring.map((point, i) => {
        const before = ring[(i + ring.length - 1) % ring.length];
        const after = ring[(i + 1) % ring.length];
        const dx = (after[1] - before[1]) * cosLat;
        const dy = after[0] - before[0];
        const length = Math.hypot(dx, dy) || 1;
        // The normal to the chord from the previous vertex to the next.
        const nx = (outwardSign * dy) / length;
        const ny = (-outwardSign * dx) / length;
        const degrees = BOUNDARY_BUFFER_METRES / METRES_PER_DEGREE_LAT;
        return [point[0] + ny * degrees, point[1] + (nx * degrees) / cosLat];
      });
    });
    return maskRings;
  }

  return {
    CITY_LIMITS,
    OUTLINE_PATHS,
    BOUNDARY_BUFFER_METRES,
    getMaskRings
  };
